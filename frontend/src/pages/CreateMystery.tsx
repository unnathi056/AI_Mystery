import React, { useState } from "react";
import { Link } from "react-router-dom";

export function CreateMystery() {
  const [scenario, setScenario] = useState("");
  const [genre, setGenre] = useState("Murder mystery");
  const [difficulty, setDifficulty] = useState("Medium");
  const [suspectsCount, setSuspectsCount] = useState("4 people");
  const [loading, setLoading] = useState(false);
  const [message, setMessage] = useState<{ type: "error" | "notice"; text: string } | null>(null);
  const [generatedCase, setGeneratedCase] = useState<any>(null);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!scenario.trim()) {
      setMessage({ type: "error", text: "Please enter a scenario to begin." });
      return;
    }

    setLoading(true);
    setMessage(null);

    try {
      // ನಿಮ್ಮ ಬ್ಯಾಕ್‌ಎಂಡ್ ರನ್ ಆಗುವ URL (ಸಾಮಾನ್ಯವಾಗಿ port 5000)
      const response = await fetch("/api/cases", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          scenario,
          genre,
          difficulty,
          suspects: [suspectsCount],
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.error || "Failed to generate case.");
      }

      setMessage({ type: "notice", text: "Case generated by Gemini & saved to MongoDB successfully!" });
      setGeneratedCase(data.data);
    } catch (err: any) {
      setMessage({ type: "error", text: err.message || "Connection error. Is your backend server running?" });
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="create-page">
      <Link to="/" className="back-link">← BACK TO HOME</Link>
      <div className="create-layout">
        <div className="create-intro">
          <span className="eyebrow"><span className="eyebrow-line"></span>CASE CREATION</span>
          <h1>Build your <em>mystery</em> casefile.</h1>
          <p>Provide a seed scenario. Our AI detective engine will craft clues, motives, and evidence layers around it.</p>
          <div className="case-stamp">
            <small>STATUS</small>
            <strong>{generatedCase ? "READY / SOLVE" : "PENDING"}</strong>
            <small>AI-DRIVEN ENGINE</small>
          </div>
        </div>

        <div className="case-form">
          <form onSubmit={handleSubmit}>
            <div className="field-label">
              THE SCENARIO <span>REQUIRED</span>
            </div>
            <textarea
              value={scenario}
              onChange={(e) => setScenario(e.target.value)}
              placeholder="A person was found missing from a locked room. Three people were present..."
              maxLength={2000}
            />
            <div className="field-meta">
              <span>A few sentences is enough to begin.</span>
              <span>{scenario.length} / 2,000</span>
            </div>

            {message && (
              <div className={`form-message ${message.type === "error" ? "form-error" : "form-notice"}`}>
                {message.text}
              </div>
            )}

            <div className="form-divider"></div>

            <div className="field-grid">
              <div className="field">
                <div className="field-label">GENRE</div>
                <select value={genre} onChange={(e) => setGenre(e.target.value)}>
                  <option value="Murder mystery">Murder mystery</option>
                  <option value="Theft / Heist">Theft / Heist</option>
                  <option value="Cyber / Tech">Cyber / Tech</option>
                </select>
              </div>
              <div className="field">
                <div className="field-label">DIFFICULTY</div>
                <select value={difficulty} onChange={(e) => setDifficulty(e.target.value)}>
                  <option value="Easy">Easy</option>
                  <option value="Medium">Medium</option>
                  <option value="Hard">Hard</option>
                </select>
              </div>
              <div className="field">
                <div className="field-label">SUSPECTS</div>
                <select value={suspectsCount} onChange={(y) => setSuspectsCount(y.target.value)}>
                  <option value="2 people">2 people</option>
                  <option value="4 people">4 people</option>
                  <option value="6 people">6 people</option>
                </select>
              </div>
            </div>

            <button type="submit" className="button button-primary form-submit" disabled={loading}>
              <span>{loading ? "Generating with AI..." : "Prepare the case"}</span>
              <span>↗</span>
            </button>
          </form>

          {generatedCase && (
            <div style={{ marginTop: "30px", background: "#191b16", padding: "20px", border: "1px solid var(--accent)" }}>
              <h3 style={{ fontFamily: "var(--serif)", color: "var(--accent)", marginTop: 0 }}>Case Successfully Generated!</h3>
              <p style={{ fontSize: "12px", color: "#d9d2bf" }}><strong>Scenario:</strong> {generatedCase.scenario}</p>
              <p style={{ fontSize: "12px", color: "#d9d2bf" }}><strong>AI Clues:</strong></p>
              <pre style={{ fontSize: "11px", background: "#11130f", padding: "10px", color: "#c9df72", overflowX: "auto" }}>
                {JSON.stringify(generatedCase.generatedClues, null, 2)}
              </pre>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
